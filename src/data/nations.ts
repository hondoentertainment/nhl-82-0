export function nationForPlayer(player: Player): FourNation | null {
  return BY_NAME[player.name] ?? null;
}

export function isFourNationsPlayer(player: Player): boolean {
  return nationForPlayer(player) != null;
}

export function playerFilterForMode(
  mode: GameMode | null,
): ((player: Player) => boolean) | undefined {
  if (mode === 'fournations') return isFourNationsPlayer;
  return undefined;
}
